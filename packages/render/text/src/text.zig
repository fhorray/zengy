/// Generates an RGBA8 pixel buffer (ATLAS_WIDTH x ATLAS_HEIGHT x 4 bytes) containing
/// all printable ASCII glyphs rendered in white with alpha 0 or 255.
pub fn generateFontAtlasRgba8(allocator: std.mem.Allocator) ![]u8 {
    const pixels = try allocator.alloc(u8, ATLAS_WIDTH * ATLAS_HEIGHT * 4);
    @memset(pixels, 0);

    for (FONT_8X8, 0..) |glyph, idx| {
        const col: u32 = @intCast(idx % ATLAS_COLS);
        const row: u32 = @intCast(idx / ATLAS_COLS);
        const base_x = col * GLYPH_W;
        const base_y = row * GLYPH_H;

        for (0..GLYPH_H) |gy| {
            const bits = glyph[gy];
            for (0..GLYPH_W) |gx| {
                const mask: u8 = @as(u8, 0x80) >> @intCast(gx);
                if ((bits & mask) != 0) {
                    const px = base_x + @as(u32, @intCast(gx));
                    const py = base_y + @as(u32, @intCast(gy));
                    const offset = (py * ATLAS_WIDTH + px) * 4;
                    pixels[offset + 0] = 255;
                    pixels[offset + 1] = 255;
                    pixels[offset + 2] = 255;
                    pixels[offset + 3] = 255;
                }
            }
        }
    }
    return pixels;
}

/// Returns normalized atlas UV coordinates for an ASCII character.
/// Non-ASCII or control characters fall back to space (' ').
pub fn glyphUv(ch: u8) UvRect {
    const idx: u32 = if (ch >= 32 and ch <= 126) ch - 32 else 0;
    const col: u32 = idx % ATLAS_COLS;
    const row: u32 = idx / ATLAS_COLS;
    const x0 = @as(f32, @floatFromInt(col * GLYPH_W));
    const y0 = @as(f32, @floatFromInt(row * GLYPH_H));
    const aw = @as(f32, @floatFromInt(ATLAS_WIDTH));
    const ah = @as(f32, @floatFromInt(ATLAS_HEIGHT));
    return .{
        .u0 = x0 / aw,
        .v0 = y0 / ah,
        .u1 = (x0 + @as(f32, @floatFromInt(GLYPH_W))) / aw,
        .v1 = (y0 + @as(f32, @floatFromInt(GLYPH_H))) / ah,
    };
}

/// Measures the bounding box of `text` at the given `scale` (1.0 = 8px, 2.0 = 16px).
pub fn measureText(text: []const u8, scale: f32) TextSize {
    const s = if (scale > 0.0) scale else 1.0;
    const advance = @as(f32, @floatFromInt(GLYPH_W)) * s;
    const line_h = @as(f32, @floatFromInt(GLYPH_H)) * s;
    var max_w: f32 = 0;
    var cur_w: f32 = 0;
    var lines: f32 = 1;

    for (text) |ch| {
        if (ch == '\n') {
            if (cur_w > max_w) max_w = cur_w;
            cur_w = 0;
            lines += 1;
        } else {
            cur_w += advance;
        }
    }
    if (cur_w > max_w) max_w = cur_w;
    return .{
        .width = max_w,
        .height = lines * line_h,
    };
}

/// Appends textured glyph quads for `text` at `(x, y)` with `scale` and `color`.
pub fn emitTextQuads(
    allocator: std.mem.Allocator,
    out_quads: *std.ArrayList(TextQuad),
    x: f32,
    y: f32,
    text: []const u8,
    scale: f32,
    color: graphics.Color,
) !void {
    const s = if (scale > 0.0) scale else 1.0;
    const gw = @as(f32, @floatFromInt(GLYPH_W)) * s;
    const gh = @as(f32, @floatFromInt(GLYPH_H)) * s;
    var cx = x;
    var cy = y;

    for (text) |ch| {
        if (ch == '\n') {
            cx = x;
            cy += gh + 2.0 * s;
            continue;
        }
        if (ch != ' ') {
            const uv = glyphUv(ch);
            try out_quads.append(allocator, .{
                .x = cx,
                .y = cy,
                .width = gw,
                .height = gh,
                .u0 = uv.u0,
                .v0 = uv.v0,
                .u1 = uv.u1,
                .v1 = uv.v1,
                .color = color,
            });
        }
        cx += gw;
    }
}
