//! Embedded Bitmap Font Atlas & Text Measurement Package (`official.text`).
//!
//! Provides a zero-dependency 8x8 ASCII (32..126) bitmap font atlas, glyph UV lookup,
//! text measurement, and quad emission for GPU text rendering without requiring
//! external font files or `SDL3_ttf` DLLs.

const std = @import("std");
const graphics = @import("graphics");

pub const GLYPH_W: u32 = 8;
pub const GLYPH_H: u32 = 8;
pub const ATLAS_COLS: u32 = 16;
pub const ATLAS_ROWS: u32 = 6;
pub const ATLAS_WIDTH: u32 = ATLAS_COLS * GLYPH_W; // 128
pub const ATLAS_HEIGHT: u32 = ATLAS_ROWS * GLYPH_H; // 48

pub const TextSize = struct {
    width: f32,
    height: f32,
};

pub const UvRect = struct {
    u0: f32,
    v0: f32,
    u1: f32,
    v1: f32,
};

pub const TextQuad = struct {
    x: f32,
    y: f32,
    width: f32,
    height: f32,
    u0: f32,
    v0: f32,
    u1: f32,
    v1: f32,
    color: graphics.Color,
};

